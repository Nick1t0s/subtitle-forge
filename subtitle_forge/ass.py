"""Small, dependency-free Advanced SubStation Alpha writer."""

from dataclasses import dataclass
import math
import re


@dataclass(frozen=True)
class StyleConfig:
    font: str = "DejaVu Sans"
    font_size: int = 54
    primary_color: str = "&H00FFFFFF"
    highlight_color: str = "&H0000FFFF"
    outline_color: str = "&H00000000"
    outline: float = 3
    shadow: float = 1
    alignment: int = 2
    margin_v: int = 70
    canvas_width: int = 1080
    canvas_height: int = 1920

    def __post_init__(self) -> None:
        for name in ("canvas_width", "canvas_height"):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
                raise ValueError(f"{name} must be a positive integer")
        if (not isinstance(self.font, str) or not self.font.strip()
                or any(char in self.font for char in ",\r\n")):
            raise ValueError("font must be non-empty and cannot contain commas or newlines")
        if not isinstance(self.font_size, int) or isinstance(self.font_size, bool) or self.font_size <= 0:
            raise ValueError("font_size must be a positive integer")
        for name in ("primary_color", "highlight_color", "outline_color"):
            value = getattr(self, name)
            if not isinstance(value, str) or re.fullmatch(r"&H[0-9A-Fa-f]{8}", value) is None:
                raise ValueError(f"{name} must be an ASS &HAABBGGRR color")
        for name in ("outline", "shadow"):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or value < 0:
                raise ValueError(f"{name} must be a finite non-negative number")
        if not isinstance(self.alignment, int) or isinstance(self.alignment, bool) or self.alignment not in range(1, 10):
            raise ValueError("alignment must be an ASS v4+ alignment from 1 to 9")
        if not isinstance(self.margin_v, int) or isinstance(self.margin_v, bool) or self.margin_v < 0:
            raise ValueError("margin_v must be a non-negative integer")


@dataclass(frozen=True)
class Event:
    start: float
    end: float
    text: str

    def __post_init__(self) -> None:
        if (isinstance(self.start, bool) or not isinstance(self.start, (int, float))
                or not math.isfinite(self.start) or self.start < 0):
            raise ValueError("event start must be a finite non-negative number")
        if (isinstance(self.end, bool) or not isinstance(self.end, (int, float))
                or not math.isfinite(self.end) or self.end <= self.start):
            raise ValueError("event end must be finite and greater than start")
        if not isinstance(self.text, str):
            raise TypeError("event text must be a string")
        if "\r" in self.text or "\n" in self.text:
            raise ValueError("event text cannot contain newlines")


def escape_text(text: str) -> str:
    """Make literal user text safe for ASS, including backslash commands."""
    if not isinstance(text, str):
        raise TypeError("text must be a string")
    # Fullwidth lookalikes are rendered as text by libass and cannot start tags
    # (including commands such as literal ``\\N`` or ``\\h``).
    text = text.replace("\\", "＼").replace("{", "｛").replace("}", "｝")
    return text.replace("\r\n", " ").replace("\r", " ").replace("\n", " ")


def _centiseconds(t: float) -> int:
    return int(math.floor(t * 100 + 0.5))


def ass_time(t: float) -> str:
    """Format seconds as ASS H:MM:SS.cc, rounding to centiseconds."""
    if isinstance(t, bool) or not isinstance(t, (int, float)) or not math.isfinite(t) or t < 0:
        raise ValueError("time must be a finite non-negative number")
    centiseconds = _centiseconds(t)
    hours, remainder = divmod(centiseconds, 360000)
    minutes, remainder = divmod(remainder, 6000)
    seconds, cs = divmod(remainder, 100)
    return f"{hours}:{minutes:02d}:{seconds:02d}.{cs:02d}"


def render_ass(events: list[Event] | tuple[Event, ...], config: StyleConfig = StyleConfig(),
               width: int = 1080, height: int = 1920) -> str:
    """Render ASS; event text is trusted, preformatted ASS from style plugins.

    Plugins must escape all literal user supplied text with :func:`escape_text`.
    """
    if not isinstance(config, StyleConfig):
        raise TypeError("config must be a StyleConfig")
    for name, dimension in (("width", width), ("height", height)):
        if not isinstance(dimension, int) or isinstance(dimension, bool) or dimension <= 0:
            raise ValueError(f"{name} must be a positive integer")
    rows = [
        "[Script Info]",
        "; Script generated by Subtitle Forge",
        "ScriptType: v4.00+",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        (f"Style: Default,{config.font.replace(',', '')},{config.font_size},{config.primary_color},"
         f"{config.highlight_color},{config.outline_color},&H80000000,0,0,0,0,100,100,0,0,1,"
         f"{config.outline:g},{config.shadow:g},{config.alignment},40,40,{config.margin_v},1"),
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    for event in events:
        if not isinstance(event, Event):
            raise TypeError("events must contain Event instances")
        # ASS stores centisecond timestamps. Tiny positive intervals can round
        # to the same timestamp, in which case omit the invalid zero-length row.
        if _centiseconds(event.end) <= _centiseconds(event.start):
            continue
        rows.append(f"Dialogue: 0,{ass_time(event.start)},{ass_time(event.end)},Default,,0,0,0,,{event.text}")
    return "\n".join(rows) + "\n"
